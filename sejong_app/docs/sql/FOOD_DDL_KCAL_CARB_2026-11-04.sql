-- 2026-11-04 식사기록(T_FOOD_TRAN)에 「그 끼니의 열량·탄수화물」 칸 추가 — 사진 등록(Gemini) 결과를 기록마다 저장하기 위해.
--   · 종전 열량 집계(getTodaysumFood)는 마스터(T_FOOD_MST.FOOD_KCAL)로만 셌다 → 마스터 없는 음식(직접입력)은 0 이었다.
--   · 이제 기록의 FOOD_KCAL 이 있으면 그 값, 없으면 마스터 값(COALESCE). 수동 입력은 두 칸이 NULL 로 들어가 종전과 같다.
--   · 다시 돌려도 안전(없을 때만 ADD).
SET @db = DATABASE();
SET @s = (SELECT IF(COUNT(*)=0, 'ALTER TABLE T_FOOD_TRAN ADD COLUMN FOOD_KCAL DECIMAL(8,1) NULL COMMENT ''이 기록의 열량(kcal, 섭취량 기준)'' AFTER FOOD_MSEQ', 'SELECT 1')
            FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=@db AND TABLE_NAME='T_FOOD_TRAN' AND COLUMN_NAME='FOOD_KCAL');
PREPARE p FROM @s; EXECUTE p; DEALLOCATE PREPARE p;
SET @s = (SELECT IF(COUNT(*)=0, 'ALTER TABLE T_FOOD_TRAN ADD COLUMN FOOD_CARB DECIMAL(8,1) NULL COMMENT ''이 기록의 탄수화물(g, 섭취량 기준)'' AFTER FOOD_KCAL', 'SELECT 1')
            FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=@db AND TABLE_NAME='T_FOOD_TRAN' AND COLUMN_NAME='FOOD_CARB');
PREPARE p FROM @s; EXECUTE p; DEALLOCATE PREPARE p;
-- 확인
SELECT COLUMN_NAME, COLUMN_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=@db AND TABLE_NAME='T_FOOD_TRAN' AND COLUMN_NAME IN ('FOOD_KCAL','FOOD_CARB');
